import {test,expect,type Page} from '@playwright/test'
const base=process.env.FRONTEND_URL||'http://127.0.0.1:5173'
const masterPassword=process.env.MASTER_PASSWORD||'LichuMaster2026!'
async function login(page:Page,username:string,password:string){await page.goto('/login');await page.getByLabel('아이디',{exact:true}).fill(username);await page.getByLabel('비밀번호',{exact:true}).fill(password);await page.getByRole('button',{name:'로그인',exact:true}).click()}

test('회원가입 → 신청 → 승인 → 반납 → 반려 → 취소 → 관리자 회수',async({page,browser})=>{
  const id=Date.now().toString(), username=`smoke${id}`, product=`Smoke SaaS ${id}`
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/signup')
  await page.getByLabel('사번').fill(`SM${id}`)
  await page.getByLabel('이름',{exact:false}).fill('스모크 테스트')
  await page.getByLabel('부서',{exact:false}).selectOption({label:'개발팀'})
  await page.getByLabel('직급 / 직책').fill('QA Engineer')
  await page.getByLabel('회사 이메일').fill(`${username}@example.com`)
  await page.getByLabel('아이디').fill(username)
  await page.getByLabel('비밀번호 *',{exact:true}).fill('SmokePassword2026!')
  await page.getByLabel('비밀번호 확인').fill('SmokePassword2026!')
  await page.getByRole('button',{name:'회원가입',exact:true}).click()
  await expect(page).toHaveURL(/login\?registered=1/)
  await login(page,username,'SmokePassword2026!')
  await expect(page).toHaveURL(/\/licenses$/)
  await page.getByRole('button',{name:'회원 정보 수정'}).click()
  await expect(page.getByRole('dialog')).toContainText('회원 정보 수정')
  await page.getByRole('button',{name:'취소',exact:true}).click()
  await page.goto('/admin');await expect(page).toHaveURL(/\/licenses$/)
  const adminContext=await browser.newContext({baseURL:base,viewport:{width:1440,height:1000}}),admin=await adminContext.newPage()
  admin.on('pageerror',e=>errors.push(e.message))
  await login(admin,'master',masterPassword)
  await expect(admin).toHaveURL(/\/admin$/)
  await admin.getByRole('link',{name:'라이선스 관리',exact:true}).click()
  await admin.getByRole('button',{name:'라이선스 등록',exact:true}).click()
  await admin.getByLabel('라이선스 이름').fill(product)
  await admin.getByLabel('공급사').fill('Smoke Vendor')
  await admin.getByLabel('플랜',{exact:true}).fill('Pro')
  await admin.getByLabel('설명',{exact:true}).fill('실제 API 기반 E2E 테스트 도구')
  await admin.getByLabel('사용자당 단가').fill('20')
  await admin.getByRole('button',{name:'저장',exact:true}).click()
  await expect(admin.getByRole('dialog')).toHaveCount(0)
  async function request(){
    await page.goto('/licenses');await page.getByLabel('라이선스 검색').fill(product)
    await page.locator('.license-card').getByRole('button',{name:'사용 신청'}).click()
    await page.getByLabel('사용 목적').fill('스모크 검증 프로젝트')
    await page.getByLabel('사용 시작 예정일').fill('2026-09-08')
    await page.getByLabel('사용 종료 예정일').fill('2026-12-31')
    await page.getByRole('button',{name:'신청하기',exact:true}).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
  }
  async function decide(kind:'승인'|'반려'){
    await admin.goto('/admin/requests')
    await admin.getByRole('row').filter({hasText:product}).getByRole('button',{name:kind,exact:true}).click()
    await admin.getByLabel(`${kind} 사유`).fill(`스모크 ${kind} 사유`)
    await admin.getByRole('button',{name:`${kind} 확정`}).click()
    await expect(admin.getByRole('dialog')).toHaveCount(0)
    await expect(admin.getByRole('row').filter({hasText:product})).toHaveCount(0)
  }
  await request();await decide('승인')
  await admin.getByRole('button',{name:'처리 이력'}).click()
  await expect(admin.getByRole('row').filter({hasText:product})).toContainText('스모크 승인 사유')
  await admin.getByLabel('처리 결과 필터').selectOption('REJECTED')
  await expect(admin.getByRole('row').filter({hasText:product})).toHaveCount(0)
  await page.goto('/requests');await expect(page.getByText('스모크 승인 사유')).toBeVisible()
  await page.goto('/my-licenses');await page.getByRole('button',{name:'반납',exact:true}).click()
  await page.getByRole('button',{name:'반납 확인'}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('현재 사용 중인 라이선스가 없습니다.')).toBeVisible()
  await request();await decide('반려')
  await page.goto('/requests');await expect(page.getByText('스모크 반려 사유')).toBeVisible()
  await request();await page.goto('/requests')
  await page.getByRole('button',{name:'신청 취소',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'신청 취소',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await request();await decide('승인')
  await admin.goto('/admin/licenses');await admin.getByLabel('라이선스 검색').fill(product)
  await admin.getByRole('button',{name:`${product} 사용자 보기`,exact:true}).click()
  await admin.getByLabel('직원 검색').fill('스')
  await expect(admin.getByRole('dialog').locator('.assignment-user-info strong').filter({hasText:'스모크 테스트'})).toBeVisible()
  await admin.getByRole('dialog').getByRole('button',{name:'수정',exact:true}).click()
  await admin.getByLabel('권한 승인 시작일').fill('2026-09-10')
  await admin.getByLabel('권한 승인 종료일').fill('2026-12-20')
  await admin.getByRole('button',{name:'저장',exact:true}).click()
  await expect(admin.getByRole('dialog')).toContainText('2026. 09. 10. ~ 2026. 12. 20.')
  await admin.getByRole('button',{name:'권한 회수',exact:true}).click()
  await admin.getByLabel('회수 사유').fill('스모크 프로젝트 종료')
  await admin.getByRole('button',{name:'권한 회수',exact:true}).click()
  await expect(admin.getByText('현재 할당된 사용자가 없습니다.')).toBeVisible()
  await admin.getByRole('button',{name:'닫기',exact:true}).click()
  await admin.getByRole('button',{name:`${product} 수정`}).click()
  await admin.getByLabel('운영 상태').selectOption('INACTIVE')
  await admin.getByRole('button',{name:'저장',exact:true}).click()
  await expect(admin.getByRole('dialog')).toHaveCount(0)
  await page.goto('/my-licenses');await expect(page.getByText('현재 사용 중인 라이선스가 없습니다.')).toBeVisible()
  expect(errors).toEqual([])
  await adminContext.close()
})

test('1440 / 1024 / 768 레이아웃, 검색 Empty 및 API Error',async({page})=>{
  await login(page,'myeongjin',process.env.DEMO_PASSWORD||'LichuDemo2026!')
  for(const width of [1440,1024,768]){
    await page.setViewportSize({width,height:1000})
    await expect(page.locator('.license-card').first()).toBeVisible()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  }
  await page.getByLabel('라이선스 검색').fill('no-matching-lic-000')
  await expect(page.getByText('조건에 맞는 라이선스가 없습니다.')).toBeVisible()
  await page.route('**/api/licenses',route=>route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({code:'TEST_ERROR',message:'테스트 서버 오류',fields:{}})}))
  await page.getByRole('button',{name:'새로고침'}).click()
  await expect(page.getByRole('alert')).toHaveText(/테스트 서버 오류/)
  await page.unroute('**/api/licenses')
  await page.getByRole('button',{name:'다시 시도'}).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
})
